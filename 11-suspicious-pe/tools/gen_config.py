#!/usr/bin/env python3
"""Generates src/config_blob.h: the RC4-encrypted configuration of the
simulated 'KestrelUpdate' sample. The RC4 key is stored XOR 0x5A."""
import os

CONFIG = ('{"c2":"https://updates.kestrel.example/api/v3/checkin",'
          '"backup":"https://cdn-kestrel.example/u/fallback",'
          '"sleep":3600,"jitter":15,"campaign":"KST-2026-Q4",'
          '"mutex":"Local\\\\KestrelUpdateMtx",'
          '"autostart":"HKCU\\\\Software\\\\Kestrel\\\\Updater\\\\RunOnLogon"}')
KEY = b"kU7!xq9#Lw2$"


def rc4(key, data):
    s = list(range(256))
    j = 0
    for i in range(256):
        j = (j + s[i] + key[i % len(key)]) & 0xFF
        s[i], s[j] = s[j], s[i]
    i = j = 0
    out = bytearray()
    for c in data:
        i = (i + 1) & 0xFF
        j = (j + s[i]) & 0xFF
        s[i], s[j] = s[j], s[i]
        out.append(c ^ s[(s[i] + s[j]) & 0xFF])
    return bytes(out)


def arr(b):
    return ", ".join("0x%02x" % x for x in b)


blob = rc4(KEY, CONFIG.encode() + b"\0")
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "config_blob.h"), "w") as f:
    f.write("/* Generated by tools/gen_config.py - do not edit. */\n#pragma once\n\n")
    f.write("static const unsigned char k_cfg_key_x[%d] = {%s};\n" % (len(KEY), arr(bytes(k ^ 0x5A for k in KEY))))
    f.write("static const unsigned char k_cfg_blob[%d] = {%s};\n" % (len(blob), arr(blob)))
with open(os.path.join(here, "..", "expected", "config.json"), "w") as f:
    f.write(CONFIG + "\n")
print("config %d bytes" % len(blob))
