#!/usr/bin/env python3
"""Generates src/libkstore/kstore_table.h: 16 door secrets, encrypted.

Plaintext secret for door d = sha256("kestrel-door-<d>")[:16]. Re-run only when
changing the scheme; the generated header is committed."""
import hashlib
import os

M64 = (1 << 64) - 1
STORE_KEY = 0x4B53544F52453231  # "KSTORE21" read big-endian


def stream(key, door, i):
    x = key ^ ((door * 0x9E3779B97F4A7C15) & M64) ^ ((i * 0xD1B54A32D192ED03) & M64)
    x ^= x >> 31
    x = (x * 0xBF58476D1CE4E5B9) & M64
    x ^= x >> 27
    return (x >> 56) & 0xFF


def secret(door):
    return hashlib.sha256(b"kestrel-door-%d" % door).digest()[:16]


def main():
    rows = []
    for door in range(1, 17):
        enc = bytes(b ^ stream(STORE_KEY, door, i) for i, b in enumerate(secret(door)))
        rows.append("    {" + ", ".join("0x%02x" % b for b in enc) + "},")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "libkstore", "kstore_table.h")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_kstore.py - do not edit. */\n"
                "#ifndef KSTORE_TABLE_H\n#define KSTORE_TABLE_H\n#include <stdint.h>\n\n"
                "#define KSTORE_KEY 0x%016xULL\n\n"
                "static const uint8_t k_door_table[16][16] = {\n%s\n};\n\n#endif\n" % (STORE_KEY, "\n".join(rows)))
    for d in (7,):
        print("door %d secret %s" % (d, secret(d).hex()))


if __name__ == "__main__":
    main()
