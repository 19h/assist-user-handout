#!/usr/bin/env python3
"""Generates src/kstr_table.h (encrypted strings) and src/pin_table.h (S-box).

Kept out of the build: the generated headers are committed, so the shipped
binary never depends on this script. Re-run only when changing the strings.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")

MUL = 6364136223846793005
INC = 1442695040888963407
M64 = (1 << 64) - 1

STRINGS = [
    ("KSTR_BANNER", "Kestrel Lockworks :: factory provisioning tool v3.2"),
    ("KSTR_USAGE", "usage: kestrel-provision <serial KS-XXXX-XXXX> <day>"),
    ("KSTR_BAD_SERIAL", "error: serial must look like KS-0000-0000"),
    ("KSTR_PIN_FMT", "UNLOCK PIN for %s (day %u): %06u\n"),
    ("KSTR_MASTER", "7F3A-99C1-D00D"),
    ("KSTR_AUDIT_LOG", "audit log: /var/kestrel/provision.log"),
    ("KSTR_ENDPOINT", "service endpoint: provisioning.kestrel.example:8443"),
    ("KSTR_OVERRIDE", "debug: factory master override accepted, all doors released"),
]


def keystream(key, n):
    k = key
    out = []
    for _ in range(n):
        k = (k * MUL + INC) & M64
        out.append(k ^ (k >> 29))
    return out


def encrypt(text, key):
    raw = text.encode() + b"\0"
    raw += b"\0" * (-len(raw) % 8)
    assert len(raw) <= 64, text
    words = [int.from_bytes(raw[i:i + 8], "little") for i in range(0, len(raw), 8)]
    ks = keystream(key, len(words))
    return [w ^ k for w, k in zip(words, ks)]


def main():
    lines = ["/* Generated by tools/gen_tables.py - do not edit. */",
             "#ifndef KSTR_TABLE_H", "#define KSTR_TABLE_H", "#include <stdint.h>", ""]
    for i, (name, _) in enumerate(STRINGS):
        lines.append("#define %s %d" % (name, i))
    lines += ["", "static const struct kstr_blob {", "    uint64_t key;", "    uint32_t nwords;",
              "    uint64_t words[8];", "} k_strings[] = {"]
    for i, (name, text) in enumerate(STRINGS):
        key = (0xC0DE0000D15EA5E5 * (i + 3) + 0x9E3779B97F4A7C15) & M64
        words = encrypt(text, key)
        body = ", ".join("0x%016xULL" % w for w in words)
        lines.append("    /* %s */ {0x%016xULL, %d, {%s}}," % (name, key, len(words), body))
    lines += ["};", "", "#endif", ""]
    with open(os.path.join(SRC, "kstr_table.h"), "w") as f:
        f.write("\n".join(lines))

    # 256-entry S-box from a xorshift generator: makes derive_unlock_pin awkward
    # to reimplement by hand (the table has to be dumped), trivial to emulate.
    x = 0x4B455354
    sbox = []
    for _ in range(256):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        sbox.append(x)
    rows = []
    for i in range(0, 256, 4):
        rows.append("    " + ", ".join("0x%08xu" % v for v in sbox[i:i + 4]) + ",")
    with open(os.path.join(SRC, "pin_table.h"), "w") as f:
        f.write("/* Generated by tools/gen_tables.py - do not edit. */\n"
                "#ifndef PIN_TABLE_H\n#define PIN_TABLE_H\n#include <stdint.h>\n\n"
                "static const uint32_t k_pin_sbox[256] = {\n" + "\n".join(rows) + "\n};\n\n#endif\n")


if __name__ == "__main__":
    main()
