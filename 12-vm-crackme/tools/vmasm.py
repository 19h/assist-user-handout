#!/usr/bin/env python3
"""Assembler for the Kestrel 'KVM' bytecode + reference disassembler.

  vmasm.py build   -> writes src/program.h (the password-check bytecode)
  vmasm.py disasm  -> disassembles the bytecode (ground truth for the demo)

Opcode numbering is deliberately non-sequential. Encoding:
  op | operands (registers are one byte, imm32 little endian, rel16 signed
  relative to the next instruction).
"""
import struct
import sys
import os

OPS = {  # name: (opcode, operand kinds)
    "HALT": (0x3C, ""),
    "LDI":  (0x91, "ri"),   # r = imm32
    "LDB":  (0x5E, "rb"),   # r = input[imm8]
    "LEN":  (0xC2, "r"),    # r = strlen(input)
    "ADD":  (0x17, "rr"),   # r1 += r2
    "SUB":  (0x2A, "rr"),   # r1 -= r2
    "XOR":  (0x88, "rr"),   # r1 ^= r2
    "MULI": (0x4D, "ri"),   # r *= imm32
    "ROL8": (0xE3, "rb"),   # r = rol8(r & 0xff, imm8)
    "ANDI": (0x76, "ri"),   # r &= imm32
    "CMPI": (0xB9, "ri"),   # Z = (r == imm32)
    "JNZ":  (0x05, "j"),    # if !Z: pc += rel16
    "JMP":  (0xD0, "j"),
    "FAIL": (0x6F, ""),     # result = 0, halt
    "OK":   (0xA4, ""),     # result = 1, halt
}

PASSWORD = b"Kestrel#VM26"


def assemble(lines):
    labels, out, fixups = {}, bytearray(), []
    for line in lines:
        if line.endswith(":"):
            labels[line[:-1]] = len(out)
            continue
        name, *args = line.replace(",", " ").split()
        op, kinds = OPS[name]
        out.append(op)
        for kind, arg in zip(kinds, args):
            if kind == "r":
                out.append(int(arg[1:]))
            elif kind == "b":
                out.append(int(arg, 0) & 0xFF)
            elif kind == "i":
                out += struct.pack("<I", int(arg, 0) & 0xFFFFFFFF)
            elif kind == "j":
                fixups.append((len(out), arg))
                out += b"\0\0"
    for pos, label in fixups:
        out[pos:pos + 2] = struct.pack("<h", labels[label] - (pos + 2))
    return bytes(out)


def program():
    lines = ["LEN r0", "CMPI r0, %d" % len(PASSWORD), "JNZ fail", "LDI r7, 0x5A"]
    for i, ch in enumerate(PASSWORD):
        k = (0x5A + 17 * i) & 0xFF          # per-position key
        rot = (i % 7) + 1
        mixed = ch ^ k
        mixed = ((mixed << rot) | (mixed >> (8 - rot))) & 0xFF
        expect = (mixed * 0x9D + i) & 0xFF   # MULI then ANDI keeps one byte
        lines += ["LDB r1, %d" % i, "LDI r2, %d" % k, "XOR r1, r2", "ROL8 r1, %d" % rot,
                  "MULI r1, 0x9D", "LDI r3, %d" % i, "ADD r1, r3", "ANDI r1, 0xFF",
                  "CMPI r1, %d" % expect, "JNZ fail"]
    lines += ["OK", "fail:", "FAIL"]
    return assemble(lines)


def disasm(code):
    rev = {op: (name, kinds) for name, (op, kinds) in OPS.items()}
    pc = 0
    while pc < len(code):
        name, kinds = rev[code[pc]]
        start, pc = pc, pc + 1
        args = []
        for kind in kinds:
            if kind == "r":
                args.append("r%d" % code[pc]); pc += 1
            elif kind == "b":
                args.append("%d" % code[pc]); pc += 1
            elif kind == "i":
                args.append("%#x" % struct.unpack_from("<I", code, pc)[0]); pc += 4
            elif kind == "j":
                rel = struct.unpack_from("<h", code, pc)[0]; pc += 2
                args.append("-> %04x" % (pc + rel))
        print("%04x  %-5s %s" % (start, name, ", ".join(args)))


if __name__ == "__main__":
    code = program()
    if sys.argv[1:] == ["disasm"]:
        disasm(code)
    else:
        here = os.path.dirname(os.path.abspath(__file__))
        with open(os.path.join(here, "..", "src", "program.h"), "w") as f:
            f.write("/* Generated by tools/vmasm.py - do not edit. */\n#pragma once\n\n")
            f.write("static const unsigned char k_check_program[%d] = {\n" % len(code))
            for i in range(0, len(code), 16):
                f.write("    " + ", ".join("0x%02x" % b for b in code[i:i + 16]) + ",\n")
            f.write("};\n")
        print("program: %d bytes, password %s" % (len(code), PASSWORD.decode()))
